"""
KanalibCan - Python API for the CAN / CAN FD channel of a KanaLin interface.

>>> KanaLin (not generated by CubeMX2) <<<

    from kanalibcan import KanalibCan, CanMessage

    with KanalibCan(bitrate=500_000, fd=True, data_bitrate=2_000_000) as bus:
        bus.send(CanMessage(0x123, bytes(range(64)), is_fd=True,
                            bitrate_switch=True))
        for msg in bus.iter_messages(timeout=1.0):
            print(msg)

Why this exists rather than just using python-can: the `gs_usb` backend that
python-can needs is CLASSIC ONLY, so CAN FD is unreachable through it even
though this firmware does FD with BRS up to 64 bytes. For classic-only work
python-can remains a perfectly good choice -- see the README.

The LIN channel of the same board is a separate library, KanalibLin. They are
independent and can run at the same time: CAN goes through the WinUSB vendor
interface and LIN through the CDC serial port.
"""

