"""
message.py - the friendly frame type.

>>> KanaLin (not generated by CubeMX2) <<<

CanMessage is what you use day to day; framing.HostFrame is the wire structure
underneath. Field names deliberately follow python-can (arbitration_id, data,
is_extended_id, is_fd, bitrate_switch), so code moves between the two with
little friction.

Two differences from python-can worth knowing:

  - is_extended_id defaults to FALSE here. python-can defaults it to True,
    which quietly turns 0x123 into a 29-bit identifier and is a classic way to
    spend an afternoon.
  - timestamp_us is the MCU's own microsecond stamp, taken inside the FDCAN
    ISR. It is not a host clock and does not drift with USB or Windows
    scheduling, which is the entire reason it exists.
"""

from __future__ import annotations

from dataclasses import dataclass

from .errors import FrameError
from .framing import HostFrame, dlc_to_len, is_valid_data_len, len_to_dlc
from .protocol import (
    GS_CAN_ECHO_ID_RX, GS_CAN_FLAG_BRS, GS_CAN_FLAG_ESI, GS_CAN_FLAG_FD,
    GS_CAN_FLAG_OVERFLOW, GS_CAN_ID_EFF_FLAG, GS_CAN_ID_EFF_MASK,
    GS_CAN_ID_ERR_FLAG, GS_CAN_ID_RTR_FLAG, GS_CAN_ID_SFF_MASK,
)


@dataclass
class CanMessage:
    """One CAN or CAN FD frame."""

    arbitration_id: int = 0
    data: bytes = b""
    is_extended_id: bool = False
    is_remote_frame: bool = False
    is_error_frame: bool = False

    # CAN FD
    is_fd: bool = False
    bitrate_switch: bool = False        # BRS: fast data phase
    error_state_indicator: bool = False  # ESI, set by the transmitter

    # Filled in on frames that come back from the device
    timestamp_us: int = 0
    is_rx: bool = True                  # False when this is the echo of our TX
    overflow: bool = False              # frames were lost before this one
    echo_id: int = GS_CAN_ECHO_ID_RX
    channel: int = 0

    @property
    def is_echo(self) -> bool:
        """True when this is the device confirming one of OUR transmissions.

        ⚠️ AN ECHO CARRIES NO PAYLOAD. The firmware builds it from the FDCAN
        Tx Event FIFO, which stores the header (identifier, DLC, flags) but not
        the data, so `data` is all zeros on an echo no matter what was sent.
        That is not corruption: an echo means "this frame really went out on
        the bus", and its value is the confirmation and the timestamp, not the
        content. If you want the bytes back, read the received copy (is_rx) --
        in loopback you get both.
        """
        return not self.is_rx

    def __post_init__(self) -> None:
        if isinstance(self.data, (bytearray, memoryview, list)):
            self.data = bytes(self.data)

    # --- derived -----------------------------------------------------------

    @property
    def dlc(self) -> int:
        """The DLC code that carries this payload (rounded up if needed)."""
        code = len_to_dlc(len(self.data), self.is_fd)
        if code == 0xFF:
            raise FrameError(
                f"{len(self.data)} bytes cannot be carried by a "
                f"{'CAN FD' if self.is_fd else 'classic CAN'} frame")
        return code

    @property
    def is_padded(self) -> bool:
        """True when the payload does not land exactly on a valid FD length.

        CAN FD has no size between 32 and 48 bytes, so a 40-byte payload goes
        out as 48 with the tail zero-filled. The receiver cannot tell the
        difference, so if it matters, carry a length yourself.
        """
        return not is_valid_data_len(len(self.data), self.is_fd)

    def __str__(self) -> str:
        idf = (f"{self.arbitration_id:08X}" if self.is_extended_id
               else f"{self.arbitration_id:03X}")
        tags = []
        if self.is_extended_id:
            tags.append("EXT")
        if self.is_fd:
            tags.append("FD")
        if self.bitrate_switch:
            tags.append("BRS")
        if self.error_state_indicator:
            tags.append("ESI")
        if self.is_remote_frame:
            tags.append("RTR")
        if self.is_error_frame:
            tags.append("ERR")
        if self.overflow:
            tags.append("OVFL")
        # An echo's data area is not the payload (see is_echo), so printing it
        # would just be a row of zeros pretending to be content.
        if self.is_echo:
            tags.append("echo (tx confirmed, no payload)")
            body = ""
        else:
            body = " ".join(f"{b:02X}" for b in self.data)
        return (f"{self.timestamp_us:>10} us  {idf:>8}  "
                f"[{len(self.data):2d}] {body:<48} {' '.join(tags)}").rstrip()

    # --- wire conversion ---------------------------------------------------

    def to_host_frame(self, echo_id: int) -> HostFrame:
        # Refuse an identifier that does not fit rather than masking it. A
        # truncated id is a frame that goes out under the wrong name and is
        # answered by the wrong node, with nothing anywhere saying so.
        limit = GS_CAN_ID_EFF_MASK if self.is_extended_id else GS_CAN_ID_SFF_MASK
        if not 0 <= self.arbitration_id <= limit:
            kind = "29-bit extended" if self.is_extended_id else "11-bit standard"
            raise FrameError(
                f"identifier 0x{self.arbitration_id:X} does not fit a {kind} "
                f"id (max 0x{limit:X}). Set is_extended_id=True for a 29-bit "
                "identifier.")

        can_id = self.arbitration_id
        if self.is_extended_id:
            can_id |= GS_CAN_ID_EFF_FLAG
        if self.is_remote_frame:
            can_id |= GS_CAN_ID_RTR_FLAG
        if self.is_error_frame:
            can_id |= GS_CAN_ID_ERR_FLAG

        flags = 0
        if self.is_fd:
            flags |= GS_CAN_FLAG_FD
        if self.bitrate_switch:
            flags |= GS_CAN_FLAG_BRS
        if self.error_state_indicator:
            flags |= GS_CAN_FLAG_ESI

        dlc = self.dlc
        # Pad to the DLC's own length; the device pads to the format slot.
        payload = self.data.ljust(dlc_to_len(dlc, self.is_fd), b"\x00")

        return HostFrame(echo_id=echo_id, can_id=can_id, can_dlc=dlc,
                         channel=self.channel, flags=flags, data=payload)

    @staticmethod
    def from_host_frame(hf: HostFrame) -> "CanMessage":
        ext = bool(hf.can_id & GS_CAN_ID_EFF_FLAG)
        mask = GS_CAN_ID_EFF_MASK if ext else GS_CAN_ID_SFF_MASK
        return CanMessage(
            arbitration_id=hf.can_id & mask,
            data=hf.data,
            is_extended_id=ext,
            is_remote_frame=bool(hf.can_id & GS_CAN_ID_RTR_FLAG),
            is_error_frame=bool(hf.can_id & GS_CAN_ID_ERR_FLAG),
            is_fd=bool(hf.flags & GS_CAN_FLAG_FD),
            bitrate_switch=bool(hf.flags & GS_CAN_FLAG_BRS),
            error_state_indicator=bool(hf.flags & GS_CAN_FLAG_ESI),
            timestamp_us=hf.timestamp_us,
            is_rx=(hf.echo_id == GS_CAN_ECHO_ID_RX),
            overflow=bool(hf.flags & GS_CAN_FLAG_OVERFLOW),
            echo_id=hf.echo_id,
            channel=hf.channel,
        )
