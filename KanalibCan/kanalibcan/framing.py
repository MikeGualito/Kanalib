    GS_ERR_BT_RANGE, GS_ERR_TOO_SHORT, GS_ERR_TRUNCATED, GS_FD_DATA_LEN,
    GS_HOST_FRAME_HEADER_LEN, GS_OK, GS_TIMESTAMP_LEN,
