@dataclass
class HwBitTiming:
    """The same timing the way the FDCAN registers take it.

    gs_usb splits the segment before the sample point into prop_seg and
    phase_seg1; the hardware only knows their sum.
    """
    prescaler: int = 0
    time_seg1: int = 0
    time_seg2: int = 0
    jump_width: int = 0

    @property
    def tq_per_bit(self) -> int:
        return 1 + self.time_seg1 + self.time_seg2   # 1 = sync segment

    def bitrate(self, clk_hz: int) -> int:
        """Bit rate this timing produces, in bit/s. 0 if it cannot."""
        if self.prescaler == 0:
            return 0
        return clk_hz // (self.prescaler * self.tq_per_bit)

    def sample_point(self) -> float:
        """Fraction of the bit that precedes the sample point."""
        return (1 + self.time_seg1) / self.tq_per_bit


def bittiming_to_hw(bt: Bittiming, data_phase: bool):
    """Translate and range-check, mirroring gs_bittiming_to_hw() in firmware.

    Returns (GS_OK, HwBitTiming) or (GS_ERR_BT_RANGE, None). Out of range must
    be refused rather than programmed: the HAL writes the fields straight into
    NBTP/DBTP with no range check of its own, so an oversized value would
    silently lose its top bits and the bus would run at a rate nobody asked
    for.
    """
    if data_phase:
        seg1_min, seg1_max = GS_BT_DTSEG1_MIN, GS_BT_DTSEG1_MAX
        seg2_min, seg2_max = GS_BT_DTSEG2_MIN, GS_BT_DTSEG2_MAX
        sjw_min, sjw_max = GS_BT_DSJW_MIN, GS_BT_DSJW_MAX
        brp_min, brp_max = GS_BT_DBRP_MIN, GS_BT_DBRP_MAX
    else:
        seg1_min, seg1_max = GS_BT_TSEG1_MIN, GS_BT_TSEG1_MAX
        seg2_min, seg2_max = GS_BT_TSEG2_MIN, GS_BT_TSEG2_MAX
        sjw_min, sjw_max = GS_BT_SJW_MIN, GS_BT_SJW_MAX
        brp_min, brp_max = GS_BT_BRP_MIN, GS_BT_BRP_MAX

    # Bound the halves BEFORE adding: the C version has to, or the u32 sum
    # wraps into something that looks perfectly legal.
    if bt.prop_seg > seg1_max or bt.phase_seg1 > seg1_max:
        return GS_ERR_BT_RANGE, None

    seg1 = bt.prop_seg + bt.phase_seg1

    if not seg1_min <= seg1 <= seg1_max:
        return GS_ERR_BT_RANGE, None
    if not seg2_min <= bt.phase_seg2 <= seg2_max:
        return GS_ERR_BT_RANGE, None
    if not sjw_min <= bt.sjw <= sjw_max:
        return GS_ERR_BT_RANGE, None
    if not brp_min <= bt.brp <= brp_max:
        return GS_ERR_BT_RANGE, None
    # A jump wider than phase_seg2 reaches past the end of the bit.
    if bt.sjw > bt.phase_seg2:
        return GS_ERR_BT_RANGE, None

    return GS_OK, HwBitTiming(prescaler=bt.brp, time_seg1=seg1,
                              time_seg2=bt.phase_seg2, jump_width=bt.sjw)


