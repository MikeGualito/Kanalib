"""
device.py - the KanaLin CAN channel over USB.

>>> KanaLin (not generated by CubeMX2) <<<

Speaks gs_usb directly over pyusb. It does NOT go through the `gs_usb` PyPI
package, and that is the point of this library: that package is classic-CAN
only (its frame type holds 8 data bytes and its bus reports CAN_20), so CAN FD
is unreachable through it even though this firmware does FD with BRS up to 64
bytes. Everything here supports both.

For classic CAN you can still use python-can if you prefer its ecosystem
(loggers, Notifier, can-isotp, udsoncan); see the README.
"""

from __future__ import annotations

import queue
import threading
import time
from typing import Iterator, Optional

import usb.core
import usb.util

from .bittiming import TimingSolution, solve
from .errors import (
    BackendMissing, ChannelStateError, DeviceBusy, DeviceNotFound,
    TransferError,
)
from .framing import BtConst, BtConstExt, DeviceConfig, DeviceState, parse_frame
from .message import CanMessage
from .protocol import (
    BREQ_KANALIN_BT_REGS, BREQ_KANALIN_DIAG, BREQ_KANALIN_STBY,
    BREQ_KANALIN_TEST_MODE, BT_REGS_LEN, DIAG_LEN, EP_IN, EP_OUT,
    GS_CAN_HOST_FORMAT_LE, GS_CAN_MODE_FD, GS_CAN_MODE_HW_TIMESTAMP,
    GS_CAN_MODE_LISTEN_ONLY, GS_CAN_MODE_LOOP_BACK, GS_CAN_MODE_ONE_SHOT,
    GS_CAN_MODE_RESET, GS_CAN_MODE_START, GS_DEVICE_BT_CONST_EXT_LEN,
    GS_DEVICE_BT_CONST_LEN, GS_DEVICE_CONFIG_LEN, GS_DEVICE_STATE_LEN,
    GS_HOST_FRAME_MAX_LEN, GS_OK, GS_USB_BREQ_BITTIMING,
    GS_USB_BREQ_BT_CONST, GS_USB_BREQ_BT_CONST_EXT,
    GS_USB_BREQ_DATA_BITTIMING, GS_USB_BREQ_DEVICE_CONFIG,
    GS_USB_BREQ_GET_STATE, GS_USB_BREQ_HOST_FORMAT, GS_USB_BREQ_MODE,
    GS_USB_BREQ_TIMESTAMP, ISO_NAMES, KANALIN_PID, KANALIN_VID, LEC_NAMES,
    STATE_NAMES, STBY_AWAKE, TEST_MODE_DEFAULT, VENDOR_INTERFACE,
    feature_names,
)

# Bulk reads MUST be a multiple of the 64-byte wMaxPacketSize: WinUSB rejects
# anything else, and the resulting pipe error then makes the NEXT, unrelated
# transfer fail with a misleading "Entity not found". 128 covers the largest
# frame (80 bytes), which arrives as 64+16.
_READ_SIZE = 128

_REQ_OUT = usb.util.CTRL_OUT | usb.util.CTRL_TYPE_VENDOR | usb.util.CTRL_RECIPIENT_INTERFACE
_REQ_IN = usb.util.CTRL_IN | usb.util.CTRL_TYPE_VENDOR | usb.util.CTRL_RECIPIENT_INTERFACE


def _backend():
    """A libusb backend, from libusb-package if pyusb has none of its own."""
    from usb.backend import libusb1
    be = libusb1.get_backend()
    if be is not None:
        return be
    try:
        import libusb_package
        be = libusb_package.get_libusb1_backend()
    except ImportError as exc:
        raise BackendMissing(
            "pyusb found no libusb backend and libusb-package is not "
            "installed. Run: pip install libusb-package") from exc
    if be is None:
        raise BackendMissing("libusb-package provided no usable backend")
    return be


def find_devices() -> list:
    """Every KanaLin device currently attached."""
    return list(usb.core.find(find_all=True, idVendor=KANALIN_VID,
                              idProduct=KANALIN_PID, backend=_backend()))


def _serial_of(dev) -> str:
    """The device's USB serial, or "" when it cannot be read right now."""
    try:
        return dev.serial_number or ""
    except (usb.core.USBError, NotImplementedError, ValueError):
        return ""


def list_devices() -> list:
    """Return the USB serial number of every KanaLin board attached.

    Each board derives its serial from the MCU's unique device ID, so this is
    what tells two of them apart: VID/PID are identical and the enumeration
    order is not stable. Pass the one you want as `KanalibCan(serial=...)`.
    """
    return [_serial_of(dev) for dev in find_devices()]


class KanalibCan:
    """The CAN / CAN FD channel of a KanaLin interface.

    Typical use:

        with KanalibCan(bitrate=500_000) as bus:
            bus.send(CanMessage(0x123, b"\\x01\\x02"))
            msg = bus.recv(timeout=1.0)

    ONE HANDLE AT A TIME. libusb on Windows will not give a second handle to
    the WinUSB interface, so no other process (and no python-can bus) may hold
    the CAN channel while this is open. The LIN channel is independent: it goes
    through the CDC serial port and can run at the same time.
    """

    def __init__(self,
                 bitrate: int = 500_000,
                 *,
                 fd: bool = False,
                 data_bitrate: Optional[int] = None,
                 loopback: bool = False,
                 listen_only: bool = False,
                 one_shot: bool = False,
                 hw_timestamp: bool = True,
                 receive_own_messages: bool = True,
                 rx_queue_size: int = 8192,
                 serial: Optional[str] = None,
                 sample_point: Optional[float] = None,
                 data_sample_point: Optional[float] = None) -> None:
        if listen_only and loopback:
            raise ValueError("listen_only and loopback are mutually exclusive")
        if fd and data_bitrate is None:
            data_bitrate = 2_000_000
        if data_bitrate is not None and not fd:
            raise ValueError("data_bitrate needs fd=True")

        self.bitrate = bitrate
        self.data_bitrate = data_bitrate
        # Sample points, as a fraction of the bit. The defaults live in
        # bittiming.py (87.5% nominal, 83.33% data) and are the ones the scope
        # measurements were taken with. They are overridable because the data
        # phase is where two FD nodes have to agree and where there is no way
        # to ask the other end what it uses: 75% and 80% are the common
        # automotive choices, and 75% is what this board itself boots with.
        self.sample_point = sample_point
        self.data_sample_point = data_sample_point
        self.fd = fd
        self.loopback = loopback
        self.listen_only = listen_only
        self.one_shot = one_shot
        self.hw_timestamp = hw_timestamp
        self.receive_own_messages = receive_own_messages
        self._serial = serial

        self._dev = None
        self._started = False
        self._ctrl_lock = threading.Lock()
        self._rx: "queue.Queue[CanMessage]" = queue.Queue(maxsize=rx_queue_size)
        self._reader: Optional[threading.Thread] = None
        self._stop = threading.Event()
        self._echo_counter = 0
        self._dropped = 0

        # Filled in by open()
        self.device_config: Optional[DeviceConfig] = None
        self.bt_const: Optional[BtConst] = None
        self.bt_const_ext: Optional[BtConstExt] = None
        self.fclk_hz: int = 0
        self.nominal_timing: Optional[TimingSolution] = None
        self.data_timing: Optional[TimingSolution] = None

    # --- lifecycle ---------------------------------------------------------

    def open(self) -> "KanalibCan":
        if self._dev is not None:
            return self

        devices = find_devices()
        if not devices:
            raise DeviceNotFound(
                f"no KanaLin device ({KANALIN_VID:04x}:{KANALIN_PID:04x}). "
                "Is it plugged in, and did WinUSB bind to interface 2?")
        if self._serial is not None:
            # Reading the serial is a live control transfer, and it throws for a
            # device whose vendor interface Windows has not finished binding to
            # WinUSB -- which happens for seconds after a board with a new
            # serial is first plugged in. Skip such a device instead of letting
            # the exception escape: a board that cannot be identified is not the
            # one that was asked for, and crashing here hides the boards that
            # ARE ready.
            attached = [(d, _serial_of(d)) for d in devices]
            devices = [d for d, s in attached if s == self._serial]
            if not devices:
                seen = ", ".join(repr(s) if s else "<unreadable>"
                                 for _, s in attached) or "none"
                raise DeviceNotFound(
                    f"no KanaLin with serial {self._serial!r}; attached: {seen}. "
                    "An <unreadable> entry usually means Windows is still "
                    "binding that device to WinUSB -- retry in a few seconds.")
        dev = devices[0]

        try:
            usb.util.claim_interface(dev, VENDOR_INTERFACE)
        except usb.core.USBError as exc:
            raise DeviceBusy(
                "could not claim the CAN interface. libusb on Windows gives "
                "only ONE handle to it: close any other script using the CAN "
                "channel (a python-can bus, docs/gs_usb_test.py, a --burst "
                f"left running). Original error: {exc}") from exc
        self._dev = dev

        try:
            # A run that ended badly leaves the channel started, and bit timing
            # can only be programmed while it is stopped. Always reset first.
            self._set_mode(GS_CAN_MODE_RESET, 0)

            self.device_config = DeviceConfig.parse(
                self._ctrl_in(GS_USB_BREQ_DEVICE_CONFIG, GS_DEVICE_CONFIG_LEN))
            self.bt_const = BtConst.parse(
                self._ctrl_in(GS_USB_BREQ_BT_CONST, GS_DEVICE_BT_CONST_LEN))
            self.fclk_hz = self.bt_const.fclk_can
            try:
                self.bt_const_ext = BtConstExt.parse(
                    self._ctrl_in(GS_USB_BREQ_BT_CONST_EXT,
                                  GS_DEVICE_BT_CONST_EXT_LEN))
            except usb.core.USBError:
                self.bt_const_ext = None      # device without the extension

            # Endianness handshake. The device always answers little-endian,
            # which is what the mainline driver expects, but the request is
            # part of the protocol so it is sent.
            self._ctrl_out(GS_USB_BREQ_HOST_FORMAT,
                           GS_CAN_HOST_FORMAT_LE.to_bytes(4, "little"))

            self._program_timing()
            self._start_channel()
        except Exception:
            self.close()
            raise
        return self

    def _program_timing(self) -> None:
        self.nominal_timing = solve(self.bitrate, self.fclk_hz,
                                    data_phase=False,
                                    sample_point=self.sample_point)
        self._ctrl_out(GS_USB_BREQ_BITTIMING,
                       self.nominal_timing.bittiming.serialize())
        if self.fd:
            self.data_timing = solve(self.data_bitrate, self.fclk_hz,
                                     data_phase=True,
                                     sample_point=self.data_sample_point)
            self._ctrl_out(GS_USB_BREQ_DATA_BITTIMING,
                           self.data_timing.bittiming.serialize())

    @property
    def mode_flags(self) -> int:
        flags = 0
        if self.fd:
            flags |= GS_CAN_MODE_FD
        if self.loopback:
            flags |= GS_CAN_MODE_LOOP_BACK
        if self.listen_only:
            flags |= GS_CAN_MODE_LISTEN_ONLY
        if self.one_shot:
            flags |= GS_CAN_MODE_ONE_SHOT
        if self.hw_timestamp:
            flags |= GS_CAN_MODE_HW_TIMESTAMP
        return flags

    def _start_channel(self) -> None:
        self._set_mode(GS_CAN_MODE_START, self.mode_flags)
        self._started = True
        self._stop.clear()
        self._reader = threading.Thread(target=self._read_loop,
                                        name="kanalibcan-rx", daemon=True)
        self._reader.start()

    def close(self) -> None:
        self._stop.set()
        if self._reader is not None:
            self._reader.join(timeout=2.0)
            self._reader = None
        if self._dev is not None:
            try:
                if self._started:
                    self._set_mode(GS_CAN_MODE_RESET, 0)
            except Exception:
                pass
            self._started = False
            try:
                usb.util.release_interface(self._dev, VENDOR_INTERFACE)
            except Exception:
                pass
            try:
                usb.util.dispose_resources(self._dev)
            except Exception:
                pass
            self._dev = None

    def __enter__(self) -> "KanalibCan":
        return self.open()

    def __exit__(self, *exc) -> None:
        self.close()

    # --- control transfers -------------------------------------------------

    def _ctrl_out(self, request: int, payload: bytes = b"",
                  value: int = 0) -> None:
        with self._ctrl_lock:
            self._dev.ctrl_transfer(_REQ_OUT, request, value,
                                    VENDOR_INTERFACE, payload, 1000)

    def _ctrl_in(self, request: int, length: int, value: int = 0) -> bytes:
        with self._ctrl_lock:
            return bytes(self._dev.ctrl_transfer(_REQ_IN, request, value,
                                                 VENDOR_INTERFACE, length,
                                                 1000))

    def _set_mode(self, mode: int, flags: int) -> None:
        from .framing import DeviceMode
        self._ctrl_out(GS_USB_BREQ_MODE, DeviceMode(mode, flags).serialize())

    # --- reader ------------------------------------------------------------

    def _read_loop(self) -> None:
        while not self._stop.is_set():
            try:
                raw = self._dev.read(EP_IN, _READ_SIZE, 100)
            except usb.core.USBError:
                continue          # timeout, or the device went away on close
            except Exception:
                return
            if not raw:
                continue
            code, hf = parse_frame(bytes(raw), self.hw_timestamp)
            if code != GS_OK or hf is None:
                continue
            msg = CanMessage.from_host_frame(hf)
            if not self.receive_own_messages and not msg.is_rx:
                continue
            try:
                self._rx.put_nowait(msg)
            except queue.Full:
                # Drop the OLDEST: on a saturated bus the newest frames are the
                # ones you still care about, and silently blocking the reader
                # would stall the device's own queue behind it.
                self._dropped += 1
                try:
                    self._rx.get_nowait()
                    self._rx.put_nowait(msg)
                except queue.Empty:
                    pass

    # --- data path ---------------------------------------------------------

    def send(self, msg: CanMessage, timeout: float = 1.0) -> int:
        """Queue a frame for transmission. Returns the echo_id it was given.

        The echo of a transmitted frame comes back through recv() with
        is_echo=True and this same echo_id, and it is emitted only once the
        frame REALLY went out (it comes from the Tx Event FIFO), not when it
        was queued -- so it is a genuine transmit confirmation and would not
        appear if arbitration were lost for good or the bus were dead.

        ⚠️ The echo carries NO payload: the Tx Event FIFO stores the header,
        not the data. See CanMessage.is_echo.
        """
        if not self._started:
            raise ChannelStateError("channel is not started")
        if msg.is_fd and not self.fd:
            raise ChannelStateError(
                "this is an FD frame but the channel was opened classic; "
                "construct KanalibCan(fd=True)")

        self._echo_counter = (self._echo_counter + 1) & 0x7FFFFFFF
        echo_id = self._echo_counter
        wire = msg.to_host_frame(echo_id).serialize(hw_timestamp=False)
        try:
            self._dev.write(EP_OUT, wire, int(timeout * 1000))
        except usb.core.USBError as exc:
            raise TransferError(f"bulk write failed: {exc}") from exc
        return echo_id

    def recv(self, timeout: Optional[float] = 1.0) -> Optional[CanMessage]:
        """Next frame, or None on timeout. timeout=None waits forever."""
        try:
            return self._rx.get(timeout=timeout)
        except queue.Empty:
            return None

    def iter_messages(self, timeout: Optional[float] = 1.0
                      ) -> Iterator[CanMessage]:
        """Yield frames until `timeout` passes with nothing arriving."""
        while True:
            msg = self.recv(timeout)
            if msg is None:
                return
            yield msg

    def flush(self) -> int:
        """Discard everything buffered. Returns how many were dropped."""
        n = 0
        while True:
            try:
                self._rx.get_nowait()
                n += 1
            except queue.Empty:
                return n

    @property
    def pending(self) -> int:
        return self._rx.qsize()

    @property
    def dropped(self) -> int:
        """Frames the host-side queue had to discard because it filled up."""
        return self._dropped

    # --- state and diagnostics ---------------------------------------------

    def get_state(self) -> DeviceState:
        return DeviceState.parse(
            self._ctrl_in(GS_USB_BREQ_GET_STATE, GS_DEVICE_STATE_LEN))

    def state_name(self) -> str:
        return STATE_NAMES.get(self.get_state().state, "?")

    def get_timestamp_us(self) -> int:
        """The MCU's microsecond clock -- the same base the frames carry."""
        return int.from_bytes(self._ctrl_in(GS_USB_BREQ_TIMESTAMP, 4),
                              "little")

    def features(self) -> list:
        return feature_names(self.bt_const.feature) if self.bt_const else []

    def read_bit_timing_registers(self) -> dict:
        """Bit timing READ BACK from NBTP/DBTP -- a KanaLin extension.

        gs_usb has no way to ask a device what timing it ended up with; it can
        only set one. Without this there is no way to tell "the device
        programmed what I asked" from "it accepted the request and threw it
        away", which is a bug that once lived here for a whole stage.
        """
        raw = self._ctrl_in(BREQ_KANALIN_BT_REGS, BT_REGS_LEN)
        v = [int.from_bytes(raw[i:i + 4], "little") for i in range(0, 36, 4)]

        def rate(presc, seg1, seg2):
            tq = 1 + seg1 + seg2
            return v[0] // (presc * tq) if presc else 0

        return {
            "fclk": v[0],
            "nominal": {"prescaler": v[1], "sjw": v[2], "seg1": v[3],
                        "seg2": v[4], "bitrate": rate(v[1], v[3], v[4])},
            "data": {"prescaler": v[5], "sjw": v[6], "seg1": v[7],
                     "seg2": v[8], "bitrate": rate(v[5], v[7], v[8])},
        }

    def diagnostics(self) -> dict:
        """KanaLin diagnostic block: test mode, PE2, errors, FD status.

        `data_last_error` is the one to read when an FD frame fails: it is the
        error code for the DATA phase of a BRS frame, so it separates "the
        frame died while arbitrating at the nominal rate" from "it died after
        the bit rate switched", which have entirely different causes.

        `iso_mode` and `tdc_value` describe the two FD settings a loopback test
        can never disagree about, because both ends of a loopback share them.

        `tx_dropped` counts frames this device was asked to send that never
        reached the bus, because the host sustained more than the bus could
        carry. Check it after any burst: a non-zero value means `send()`
        returned normally for frames that do not exist as far as the other
        node is concerned.
        """
        raw = self._ctrl_in(BREQ_KANALIN_DIAG, DIAG_LEN)
        v = [int.from_bytes(raw[i:i + 4], "little")
             for i in range(0, DIAG_LEN, 4)]
        return {
            "test_mode": v[0],
            "stby_drive": v[1],
            "pe2_level": v[2],          # read from the PIN, not the variable
            "last_error_code": v[3],
            "last_error": LEC_NAMES.get(v[3], "?"),
            "tx_err": v[4],
            "rx_err": v[5],
            "data_last_error_code": v[6],
            "data_last_error": LEC_NAMES.get(v[6], "?"),
            "tdc_value": v[7],          # 0 while TDC stays disabled
            "iso_mode": v[8],
            "iso": ISO_NAMES.get(v[8], "?"),
            "tx_dropped": v[9],
        }

    def set_test_mode(self, mode: int = TEST_MODE_DEFAULT) -> None:
        """Force the FDCAN mode (KanaLin extension; applied on next start).

        gs_usb cannot ask for external loopback, so without this you would have
        to recompile to change it.
        """
        self._ctrl_out(BREQ_KANALIN_TEST_MODE, b"", value=mode)

    def set_standby(self, value: int = STBY_AWAKE) -> None:
        """Drive PE2 by hand. NOTE: HIGH means the transceiver is ASLEEP."""
        self._ctrl_out(BREQ_KANALIN_STBY, b"", value=value)

    def describe(self) -> str:
        lines = [
            f"KanaLin CAN channel, fclk {self.fclk_hz} Hz",
            f"  features   {', '.join(self.features())}",
        ]
        if self.device_config:
            lines.append(f"  versions   sw={self.device_config.sw_version} "
                         f"hw={self.device_config.hw_version}")
        if self.nominal_timing:
            lines.append(f"  nominal    {self.nominal_timing.describe()}")
        if self.data_timing:
            lines.append(f"  data (FD)  {self.data_timing.describe()}")
        mode = []
        if self.fd:
            mode.append("FD")
        if self.loopback:
            mode.append("internal loopback (nothing reaches CAN_H/L)")
        if self.listen_only:
            mode.append("listen-only (never acknowledges)")
        if self.one_shot:
            mode.append("one-shot")
        if self.hw_timestamp:
            mode.append("hw timestamps")
        lines.append(f"  mode       {', '.join(mode) or 'normal'}")
        return "\n".join(lines)
