# DLC code -> byte count, for CAN FD. Codes 0..8 are the count itself.
_FD_DLC_LEN = [0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64]


def dlc_to_len(dlc: int, fd: bool) -> int:
    """DLC code -> number of data bytes.

    For classic CAN the codes 9..15 all mean 8 bytes; for FD they mean
    12/16/20/24/32/48/64.
    """
    if dlc > 15:
        raise ValueError(f"DLC code out of range: {dlc}")
    if not fd:
        return min(dlc, 8)
    return _FD_DLC_LEN[dlc]


def len_to_dlc(length: int, fd: bool) -> int:
    """Number of data bytes -> DLC code, rounding UP to the next valid code.

    CAN FD has no length between, say, 33 and 48 bytes, so a 40-byte payload
    travels as a 48-byte one. Returns 0xFF when the length cannot be
    represented at all.
    """
    if length <= 8:
        return length
    if not fd:
        return 0xFF
    for code in range(9, 16):
        if length <= _FD_DLC_LEN[code]:
            return code
    return 0xFF


def is_valid_data_len(length: int, fd: bool) -> bool:
    """True if `length` is exactly representable, with no padding needed."""
    code = len_to_dlc(length, fd)
    return code != 0xFF and dlc_to_len(code, fd) == length


@dataclass
class HostFrame:
    """A decoded gs_host_frame -- the wire structure, not the friendly one."""

    echo_id: int = GS_CAN_ECHO_ID_RX
    can_id: int = 0
    can_dlc: int = 0          # DLC code, NOT a byte count
    channel: int = 0
    flags: int = 0
    reserved: int = 0
    data: bytes = b""
    timestamp_us: int = 0

    @property
    def is_fd(self) -> bool:
        return bool(self.flags & GS_CAN_FLAG_FD)

    @property
    def data_len(self) -> int:
        return dlc_to_len(self.can_dlc, self.is_fd)

    @property
    def data_slot(self) -> int:
        """Data bytes the wire format reserves, whatever the DLC says."""
        return GS_FD_DATA_LEN if self.is_fd else GS_CLASSIC_DATA_LEN

    def wire_len(self, hw_timestamp: bool) -> int:
        """Bytes this frame takes on the wire.

        The size follows the FORMAT, never the DLC: 20/24 for a classic frame
        and 76/80 for an FD one. gs_usb reads the timestamp at a fixed offset,
        so trimming the data area would move it out from under the reader.
        """
        n = GS_HOST_FRAME_HEADER_LEN + self.data_slot
        return n + GS_TIMESTAMP_LEN if hw_timestamp else n

    def serialize(self, hw_timestamp: bool = False) -> bytes:
        # Zero-fill the slot past what the DLC covers: those bytes are padding
        # in the true sense, so no information is invented.
        payload = self.data[:self.data_len].ljust(self.data_slot, b"\x00")
        out = struct.pack(
            "<IIBBBB",
            self.echo_id & 0xFFFFFFFF,
            self.can_id & 0xFFFFFFFF,
            self.can_dlc & 0xFF,
            self.channel & 0xFF,
            self.flags & 0xFF,
            self.reserved & 0xFF,
        ) + payload
        if hw_timestamp:
            out += struct.pack("<I", self.timestamp_us & 0xFFFFFFFF)
        return out


def parse_frame(buf: bytes, hw_timestamp: bool = False):
    """Parse a packet coming from the device.

    Returns (code, frame); frame is None when code != GS_OK.

    Tolerant about length on purpose: the data area is padded out to the slot
    of the format, so there are more bytes than the DLC needs. When
    hw_timestamp is set the timestamp is read at the FIXED offset of that slot
    (20 classic, 76 FD) -- never at one derived from the DLC.
    """
    if len(buf) < GS_HOST_FRAME_HEADER_LEN:
        return GS_ERR_TOO_SHORT, None

    echo_id, can_id, can_dlc, channel, flags, reserved = struct.unpack_from(
        "<IIBBBB", buf, 0)
    if can_dlc > 15:
        return GS_ERR_BAD_DLC, None

    fd = bool(flags & GS_CAN_FLAG_FD)
    n = dlc_to_len(can_dlc, fd)
    avail = len(buf) - GS_HOST_FRAME_HEADER_LEN
    if avail < n:
        return GS_ERR_TRUNCATED, None

    slot = GS_FD_DATA_LEN if fd else GS_CLASSIC_DATA_LEN
    ts = 0
    if hw_timestamp:
        off = GS_HOST_FRAME_HEADER_LEN + slot
        if len(buf) >= off + GS_TIMESTAMP_LEN:
            ts = int.from_bytes(buf[off:off + GS_TIMESTAMP_LEN], "little")

    return GS_OK, HostFrame(
        echo_id=echo_id, can_id=can_id, can_dlc=can_dlc, channel=channel,
        flags=flags, reserved=reserved,
        data=bytes(buf[GS_HOST_FRAME_HEADER_LEN:GS_HOST_FRAME_HEADER_LEN + n]),
        timestamp_us=ts,
    )


