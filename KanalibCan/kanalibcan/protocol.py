# --- gs_device_state.state (the CAN_STATE_* of SocketCAN) -------------------
GS_CAN_STATE_ERROR_ACTIVE = 0
GS_CAN_STATE_ERROR_WARNING = 1
GS_CAN_STATE_ERROR_PASSIVE = 2
GS_CAN_STATE_BUS_OFF = 3
GS_CAN_STATE_STOPPED = 4
GS_CAN_STATE_SLEEPING = 5

