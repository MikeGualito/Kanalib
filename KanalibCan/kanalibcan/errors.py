"""
errors.py - exceptions raised by KanalibCan.

>>> KanaLin (not generated by CubeMX2) <<<

The messages carry the likely CAUSE where one is known, because the raw USB
error almost never points at it: libusb reports "Entity not found" for a wedged
pipe, "Access denied" for a second handle, and a bare pipe error for a request
the firmware stalled on purpose.
"""

from __future__ import annotations


class KanalibCanError(Exception):
    """Base class for everything this package raises."""


class DeviceNotFound(KanalibCanError):
    """No KanaLin device on the bus, or it is not the WinUSB interface."""


class BackendMissing(KanalibCanError):
    """pyusb has no libusb backend.

    On Windows pyusb ships no DLL of its own; the libusb-package wheel has one.
    """


class DeviceBusy(KanalibCanError):
    """Another process (or another handle in this one) already owns it.

    libusb on Windows gives exactly ONE handle to the WinUSB interface. Two
    scripts touching the CAN channel at the same time is the usual cause, and
    the second one fails here rather than misbehaving later.
    """


class ChannelStateError(KanalibCanError):
    """The channel is in the wrong state for what was asked.

    The common one: bit timing can only be programmed while the channel is
    STOPPED, because NBTP/DBTP are writable only with the peripheral held in
    initialisation. Call stop() first.
    """


class BitTimingError(KanalibCanError):
    """The requested bit timing is impossible or outside the device limits.

    Refusing beats programming a truncated value: the HAL writes the fields
    straight into the register with no range check, so an oversized value would
    silently lose its top bits and the bus would run at a rate nobody chose.
    """


class FrameError(KanalibCanError):
    """A frame could not be built or decoded."""


class TransferError(KanalibCanError):
    """A USB transfer failed."""
