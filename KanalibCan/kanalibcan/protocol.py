# What the host sends in gs_host_config.byte_order. The device answers
# little-endian regardless, which is what the mainline driver expects.
GS_CAN_HOST_FORMAT_LE = 0x0000BEEF

# --- Serialized lengths of the control payloads -----------------------------
GS_HOST_CONFIG_LEN = 4
GS_DEVICE_CONFIG_LEN = 12
GS_DEVICE_BT_CONST_LEN = 40
GS_DEVICE_BT_CONST_EXT_LEN = 72
GS_DEVICE_BITTIMING_LEN = 20
GS_DEVICE_MODE_LEN = 8
GS_DEVICE_STATE_LEN = 12
GS_IDENTIFY_MODE_LEN = 4
GS_TERMINATION_STATE_LEN = 4

# --- Parse error codes ------------------------------------------------------
GS_OK = 0
GS_ERR_TOO_SHORT = -1
GS_ERR_BAD_DLC = -2
GS_ERR_TRUNCATED = -3
GS_ERR_BT_RANGE = -4

# --- Bit-timing limits of this FDCAN ----------------------------------------
# These are what the device publishes in BT_CONST / BT_CONST_EXT *and* what it
# enforces before touching a register. A device that advertises one set of
# limits and applies another is worse than one that validates nothing.
GS_BT_TSEG1_MIN, GS_BT_TSEG1_MAX = 2, 256
GS_BT_TSEG2_MIN, GS_BT_TSEG2_MAX = 2, 128
GS_BT_SJW_MIN, GS_BT_SJW_MAX = 1, 128
GS_BT_BRP_MIN, GS_BT_BRP_MAX, GS_BT_BRP_INC = 1, 512, 1

GS_BT_DTSEG1_MIN, GS_BT_DTSEG1_MAX = 1, 32
GS_BT_DTSEG2_MIN, GS_BT_DTSEG2_MAX = 1, 16
GS_BT_DSJW_MIN, GS_BT_DSJW_MAX = 1, 16
GS_BT_DBRP_MIN, GS_BT_DBRP_MAX, GS_BT_DBRP_INC = 1, 32, 1

# The FDCAN kernel clock on this board, read back from the device at open()
# rather than trusted from here. Kept as the expected value.
EXPECTED_FCLK_HZ = 144_000_000

# --- KanaLin test modes (BREQ_KANALIN_TEST_MODE) ----------------------------
TEST_MODE_DEFAULT = 0     # obey the gs_usb mode flags
TEST_MODE_NORMAL = 1      # force normal mode (drives a real bus)
TEST_MODE_INTERNAL = 2    # internal loopback: no bus, no second node needed
TEST_MODE_EXTERNAL = 3    # drives the transceiver, still self-received
TEST_MODE_MONITOR = 4     # bus monitoring (listen only)

# BREQ_KANALIN_STBY values for PE2. NOTE the polarity: on the MCP2562FD, STBY
# HIGH means the transceiver is ASLEEP. Confirmed by measurement (ACK vs BIT0).
STBY_AWAKE = 0
STBY_ASLEEP = 1

# last_error_code values reported by BREQ_KANALIN_DIAG. The same table decodes
# data_last_error_code, which is the identical field for the data phase of a
# BRS frame -- the only one that moves when a frame fails after the bit rate
# switch rather than while arbitrating.
LEC_NAMES = {0: "NONE", 1: "STUFF", 2: "FORM", 3: "ACK", 4: "BIT1",
             5: "BIT0", 6: "CRC", 7: "NO_CHANGE"}

# iso_mode as reported by BREQ_KANALIN_DIAG. Two nodes that disagree here trade
# classic frames perfectly and fail EVERY FD frame, so it is read back from the
# peripheral rather than assumed.
ISO_NAMES = {0: "NON_ISO (Bosch CAN FD)", 1: "ISO 11898-1:2015"}


def feature_names(mask: int) -> list:
    """Human-readable list of the feature bits set in `mask`."""
    return [name for bit, name in FEATURE_NAMES.items() if mask & bit]
