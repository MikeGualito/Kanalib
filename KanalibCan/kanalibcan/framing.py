@dataclass
class BtConst:
    feature: int = 0
    fclk_can: int = 0
    tseg1_min: int = 0
    tseg1_max: int = 0
    tseg2_min: int = 0
    tseg2_max: int = 0
    sjw_max: int = 0
    brp_min: int = 0
    brp_max: int = 0
    brp_inc: int = 0

    def serialize(self) -> bytes:
        return struct.pack("<10I", self.feature, self.fclk_can,
                           self.tseg1_min, self.tseg1_max,
                           self.tseg2_min, self.tseg2_max, self.sjw_max,
                           self.brp_min, self.brp_max, self.brp_inc)

    @staticmethod
    def parse(buf: bytes) -> "BtConst":
        return BtConst(*struct.unpack_from("<10I", buf, 0))


@dataclass
class BtConstExt:
    nominal: BtConst = field(default_factory=BtConst)
    dtseg1_min: int = 0
    dtseg1_max: int = 0
    dtseg2_min: int = 0
    dtseg2_max: int = 0
    dsjw_max: int = 0
    dbrp_min: int = 0
    dbrp_max: int = 0
    dbrp_inc: int = 0

    def serialize(self) -> bytes:
        return self.nominal.serialize() + struct.pack(
            "<8I", self.dtseg1_min, self.dtseg1_max, self.dtseg2_min,
            self.dtseg2_max, self.dsjw_max,
            self.dbrp_min, self.dbrp_max, self.dbrp_inc)

    @staticmethod
    def parse(buf: bytes) -> "BtConstExt":
        return BtConstExt(BtConst.parse(buf),
                          *struct.unpack_from("<8I", buf, 40))


@dataclass
class DeviceConfig:
    icount: int = 0        # number of channels minus one
    sw_version: int = 0
    hw_version: int = 0

    def serialize(self) -> bytes:
        # Three reserved bytes come first, then icount, then the two versions.
        return struct.pack("<BBBBII", 0, 0, 0, self.icount & 0xFF,
                           self.sw_version, self.hw_version)

    @staticmethod
    def parse(buf: bytes) -> "DeviceConfig":
        _, _, _, icount, sw, hw = struct.unpack_from("<BBBBII", buf, 0)
        return DeviceConfig(icount, sw, hw)


