"""
bittiming.py - work out a bit timing for a target rate on this board.

>>> KanaLin (not generated by CubeMX2) <<<

gs_usb expresses a timing as prop_seg / phase_seg1 / phase_seg2 / sjw / brp,
and the device validates it against the limits it publishes in BT_CONST. This
module turns "I want 500 kbit/s" into such a timing.

WHAT IS MEASURED AND WHAT IS COMPUTED
-------------------------------------
The nominal 500 kbit/s and 250 kbit/s timings, and the 2 Mbit/s data timing,
have been confirmed ON THE WIRE with an oscilloscope:

    arbitration bit  1998 ns  (nominal 2000)  -> 72 quanta at brp=4
    data phase bit    497 ns  (nominal  500)  -> 18 quanta at brp=4
    frame at 250k vs 500k: 395 us vs 197 us   (ratio 2.005)

The solver here is tuned so that it REPRODUCES those exact timings rather than
some other arithmetically valid answer, and the self-test asserts it. Any other
rate is computed by the same rule but has never been on a scope; treat it as
arithmetic, and remember the device verifies by reading NBTP/DBTP back, which
is blind to an error shared by both sides.
"""

from __future__ import annotations

from dataclasses import dataclass

from .errors import BitTimingError
from .framing import Bittiming, HwBitTiming, bittiming_to_hw
from .protocol import (
    EXPECTED_FCLK_HZ, GS_BT_BRP_MAX, GS_BT_BRP_MIN, GS_BT_DBRP_MAX,
    GS_BT_DBRP_MIN, GS_BT_DSJW_MAX, GS_BT_DTSEG1_MAX, GS_BT_DTSEG1_MIN,
    GS_BT_DTSEG2_MAX, GS_BT_DTSEG2_MIN, GS_BT_SJW_MAX, GS_BT_TSEG1_MAX,
    GS_BT_TSEG1_MIN, GS_BT_TSEG2_MAX, GS_BT_TSEG2_MIN, GS_OK,
)

# Sample points. 87.5% is the CiA recommendation for the arbitration phase;
# the data phase runs earlier because the bit is short.
SAMPLE_POINT_NOMINAL = 0.875
SAMPLE_POINT_DATA = 1.0 - 1.0 / 6.0        # 83.33%

# Largest number of time quanta per bit the solver will pick. Without a cap it
# would always choose brp=1 and the widest possible bit (288 quanta at 500k),
# which is legal but is not what this project measured. These caps make the
# solver land on the scope-confirmed timings.
MAX_TQ_NOMINAL = 80
MAX_TQ_DATA = 20
MIN_TQ = 8                                  # below this the sample point is coarse


@dataclass(frozen=True)
class TimingSolution:
    """A solved timing, with everything needed to judge it."""
    bittiming: Bittiming
    hw: HwBitTiming
    fclk_hz: int
    requested_bitrate: int

    @property
    def actual_bitrate(self) -> int:
        return self.hw.bitrate(self.fclk_hz)

    @property
    def sample_point(self) -> float:
        return self.hw.sample_point()

    @property
    def tq_per_bit(self) -> int:
        return self.hw.tq_per_bit

    @property
    def error(self) -> float:
        """Relative rate error, 0.0 when exact."""
        if self.requested_bitrate == 0:
            return 0.0
        return (self.actual_bitrate - self.requested_bitrate) / self.requested_bitrate

    def describe(self) -> str:
        return (f"{self.actual_bitrate} bit/s "
                f"(asked {self.requested_bitrate}, error {self.error * 100:+.3f}%) "
                f"brp={self.hw.prescaler} tq={self.tq_per_bit} "
                f"seg1={self.hw.time_seg1} seg2={self.hw.time_seg2} "
                f"sjw={self.hw.jump_width} SP={self.sample_point * 100:.1f}%")


def solve(bitrate: int, fclk_hz: int = EXPECTED_FCLK_HZ,
          data_phase: bool = False,
          sample_point: float = None) -> TimingSolution:
    """Find a timing for `bitrate`, or raise BitTimingError.

    Only EXACT divisions are accepted: if fclk cannot produce the rate without
    rounding, this raises rather than quietly handing back a bus that runs at
    the wrong speed. On a 144 MHz clock the usual automotive rates are all
    exact; 5 Mbit/s, for instance, is not (144/5 = 28.8) and is refused.
    """
    if bitrate <= 0:
        raise BitTimingError(f"bit rate must be positive, got {bitrate}")

    if sample_point is None:
        sample_point = SAMPLE_POINT_DATA if data_phase else SAMPLE_POINT_NOMINAL

    if data_phase:
        max_tq = MAX_TQ_DATA
        seg1_min, seg1_max = GS_BT_DTSEG1_MIN, GS_BT_DTSEG1_MAX
        seg2_min, seg2_max = GS_BT_DTSEG2_MIN, GS_BT_DTSEG2_MAX
        brp_min, brp_max = GS_BT_DBRP_MIN, GS_BT_DBRP_MAX
        sjw_max = GS_BT_DSJW_MAX
    else:
        max_tq = MAX_TQ_NOMINAL
        seg1_min, seg1_max = GS_BT_TSEG1_MIN, GS_BT_TSEG1_MAX
        seg2_min, seg2_max = GS_BT_TSEG2_MIN, GS_BT_TSEG2_MAX
        brp_min, brp_max = GS_BT_BRP_MIN, GS_BT_BRP_MAX
        sjw_max = GS_BT_SJW_MAX

    total = fclk_hz // bitrate
    if total * bitrate != fclk_hz:
        raise BitTimingError(
            f"{bitrate} bit/s is not exactly reachable from a {fclk_hz} Hz "
            f"clock ({fclk_hz / bitrate:.4f} quanta-prescaler products); "
            "pick a rate that divides the clock exactly")

    # Prefer the widest bit within the cap: more quanta means a finer sample
    # point and more room for resynchronisation.
    for tq in range(min(max_tq, total), MIN_TQ - 1, -1):
        if total % tq:
            continue
        brp = total // tq
        if not brp_min <= brp <= brp_max:
            continue

        seg1 = max(seg1_min, min(seg1_max, round(sample_point * tq) - 1))
        seg2 = tq - 1 - seg1
        if not seg2_min <= seg2 <= seg2_max:
            continue

        sjw = min(4, seg2, sjw_max)
        bt = Bittiming(prop_seg=0, phase_seg1=seg1, phase_seg2=seg2,
                       sjw=sjw, brp=brp)
        code, hw = bittiming_to_hw(bt, data_phase)
        if code != GS_OK:
            continue
        if hw.bitrate(fclk_hz) != bitrate:
            continue
        return TimingSolution(bittiming=bt, hw=hw, fclk_hz=fclk_hz,
                              requested_bitrate=bitrate)

    raise BitTimingError(
        f"no timing within the device limits produces {bitrate} bit/s from "
        f"{fclk_hz} Hz (tried {MIN_TQ}..{max_tq} quanta per bit)")


def describe_supported(fclk_hz: int = EXPECTED_FCLK_HZ,
                       data_phase: bool = False) -> list:
    """Rates from a common list that this clock can produce exactly."""
    common = ([1_000_000, 2_000_000, 4_000_000, 5_000_000, 8_000_000]
              if data_phase else
              [10_000, 20_000, 50_000, 100_000, 125_000, 250_000, 500_000,
               800_000, 1_000_000])
    out = []
    for rate in common:
        try:
            out.append(solve(rate, fclk_hz, data_phase))
        except BitTimingError:
            pass
    return out
