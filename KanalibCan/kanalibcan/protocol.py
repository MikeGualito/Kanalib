"""
protocol.py - gs_usb wire constants for the KanaLin CAN channel.

>>> KanaLin (not generated by CubeMX2) <<<

Transcribed from KanaLin_cmake/generated/middleware/gs_framing.h. These values
are the contract with the firmware; a differential test
(tools/gs_framing_test.py) checks that the C and the Python reference agree
byte for byte, and this module carries the same numbers.

Everything on the wire is little-endian.
"""

from __future__ import annotations

# --- USB identity -----------------------------------------------------------
# The vendor interface of the composite device. CDC (the LIN channel) owns
# interfaces 0 and 1, so the CAN interface is number 2 -- a classic source of
# confusion when writing host code.
KANALIN_VID = 0x0483
KANALIN_PID = 0x5710
VENDOR_INTERFACE = 2
EP_IN = 0x83
EP_OUT = 0x02

# --- Wire geometry of gs_host_frame -----------------------------------------
# The header is 12 bytes, NOT 16:
#     echo_id u32 @0, can_id u32 @4, can_dlc u8 @8, channel u8 @9,
#     flags u8 @10, reserved u8 @11, then the data area, then the timestamp.
GS_HOST_FRAME_HEADER_LEN = 12
GS_CLASSIC_DATA_LEN = 8
GS_FD_DATA_LEN = 64
GS_TIMESTAMP_LEN = 4
GS_HOST_FRAME_MAX_LEN = (GS_HOST_FRAME_HEADER_LEN + GS_FD_DATA_LEN
                         + GS_TIMESTAMP_LEN)

# The packet size follows the FORMAT, never the DLC: 20/24 bytes for any
# classic frame and 76/80 for any FD one. gs_usb reads the timestamp at a fixed
# offset, so a packet trimmed to the DLC would put it where nobody looks.
CLASSIC_PACKET_LEN = GS_HOST_FRAME_HEADER_LEN + GS_CLASSIC_DATA_LEN        # 20
CLASSIC_PACKET_LEN_TS = CLASSIC_PACKET_LEN + GS_TIMESTAMP_LEN              # 24
FD_PACKET_LEN = GS_HOST_FRAME_HEADER_LEN + GS_FD_DATA_LEN                  # 76
FD_PACKET_LEN_TS = FD_PACKET_LEN + GS_TIMESTAMP_LEN                        # 80

# echo_id of a frame genuinely received from the bus. Anything else is the echo
# of a frame the host asked to transmit, carrying the host's own id back.
GS_CAN_ECHO_ID_RX = 0xFFFFFFFF

# --- can_id bits (the CAN_*_FLAG values of SocketCAN) -----------------------
GS_CAN_ID_EFF_FLAG = 0x80000000     # extended (29-bit) identifier
GS_CAN_ID_RTR_FLAG = 0x40000000     # remote frame
GS_CAN_ID_ERR_FLAG = 0x20000000     # error frame
GS_CAN_ID_SFF_MASK = 0x000007FF     # 11-bit identifier
GS_CAN_ID_EFF_MASK = 0x1FFFFFFF     # 29-bit identifier

# --- gs_host_frame.flags ----------------------------------------------------
GS_CAN_FLAG_OVERFLOW = 0x01         # frames were lost before this one
GS_CAN_FLAG_FD = 0x02               # CAN FD frame
GS_CAN_FLAG_BRS = 0x04              # bit rate switch (fast data phase)
GS_CAN_FLAG_ESI = 0x08              # error state indicator

# --- Control requests (bRequest of the vendor requests on EP0) --------------
GS_USB_BREQ_HOST_FORMAT = 0
GS_USB_BREQ_BITTIMING = 1
GS_USB_BREQ_MODE = 2
GS_USB_BREQ_BERR = 3
GS_USB_BREQ_BT_CONST = 4
GS_USB_BREQ_DEVICE_CONFIG = 5
GS_USB_BREQ_TIMESTAMP = 6
GS_USB_BREQ_IDENTIFY = 7
GS_USB_BREQ_GET_USER_ID = 8
GS_USB_BREQ_SET_USER_ID = 9
GS_USB_BREQ_DATA_BITTIMING = 10
GS_USB_BREQ_BT_CONST_EXT = 11
GS_USB_BREQ_SET_TERMINATION = 12
GS_USB_BREQ_GET_TERMINATION = 13
GS_USB_BREQ_GET_STATE = 14

# --- KanaLin diagnostic requests -- NOT part of gs_usb ----------------------
# Chosen well clear of the 0..14 range of gs_usb and of the 0x1A used by the
# WCID/WinUSB descriptor. They exist because gs_usb has no way to ask a device
# what it is actually doing, and that distinction has repeatedly been the
# difference between a real diagnosis and a wrong one.
BREQ_KANALIN_ECHO_SETUP = 0x40      # the setup packet as the firmware saw it
BREQ_KANALIN_TEST_MODE = 0x41       # force the FDCAN mode
BREQ_KANALIN_STBY = 0x42            # drive PE2 (transceiver standby) by hand
BREQ_KANALIN_DIAG = 0x43            # test mode, PE2 level, last error, counters
BREQ_KANALIN_BT_REGS = 0x44         # bit timing READ BACK from NBTP/DBTP

DIAG_LEN = 40                       # 10 u32
BT_REGS_LEN = 36                    # 9 u32

# --- gs_device_mode.mode ----------------------------------------------------
GS_CAN_MODE_RESET = 0
GS_CAN_MODE_START = 1

# --- gs_device_mode.flags ---------------------------------------------------
GS_CAN_MODE_LISTEN_ONLY = 1 << 0
GS_CAN_MODE_LOOP_BACK = 1 << 1
GS_CAN_MODE_TRIPLE_SAMPLE = 1 << 2
GS_CAN_MODE_ONE_SHOT = 1 << 3
GS_CAN_MODE_HW_TIMESTAMP = 1 << 4
GS_CAN_MODE_PAD_PKTS_TO_MAX_PKT_SIZE = 1 << 7
GS_CAN_MODE_FD = 1 << 8
GS_CAN_MODE_BERR_REPORTING = 1 << 12

# --- gs_device_bt_const.feature ---------------------------------------------
GS_CAN_FEATURE_LISTEN_ONLY = 1 << 0
GS_CAN_FEATURE_LOOP_BACK = 1 << 1
GS_CAN_FEATURE_TRIPLE_SAMPLE = 1 << 2
GS_CAN_FEATURE_ONE_SHOT = 1 << 3
GS_CAN_FEATURE_HW_TIMESTAMP = 1 << 4
GS_CAN_FEATURE_IDENTIFY = 1 << 5
GS_CAN_FEATURE_USER_ID = 1 << 6
GS_CAN_FEATURE_PAD_PKTS_TO_MAX_PKT_SIZE = 1 << 7
GS_CAN_FEATURE_FD = 1 << 8
GS_CAN_FEATURE_REQ_USB_QUIRK_LPC546XX = 1 << 9
GS_CAN_FEATURE_BT_CONST_EXT = 1 << 10
GS_CAN_FEATURE_TERMINATION = 1 << 11
GS_CAN_FEATURE_BERR_REPORTING = 1 << 12
GS_CAN_FEATURE_GET_STATE = 1 << 13

